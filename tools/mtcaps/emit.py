def emit_stamp(out, meta, canonical):
    """resolved.stamp exists because two of `check`'s three callers have no
    manifest. The macOS engine-target backstop and the Windows pre-build target run
    INSIDE the engine project, where the only input is $MT_OUT -- whose key carries
    <app> as a directory name, not a path to c64d/mtengine.caps. So the stamp
    records every resolve input verbatim, and those callers use
    `mtcaps check --stamp <path> --resolved <string>`.

    Without it a backstop can verify only that $MT_OUT is DEFINED, which is a
    presence test and should not be called an agreement check."""
    data = dict(meta)
    data["resolved"] = canonical
    path = os.path.join(out, "resolved.stamp")
    _write(path, json.dumps(data, indent=2, sort_keys=True) + "\n")
    return path


def emit_overrides(out, overrides, meta):
    """A per-build file inside the isolated output root, passed to `check`
    explicitly with --overrides.

    Not beside the app manifest: that is one fixed path per app, so two concurrent
    matrix jobs write and delete each other's overrides and each may resolve with
    the other's keys or with none. A matrix is by definition many builds of one app
    at once, so the fixed-path design broke the exact case it existed to serve.
    Here, two variants have two roots and cannot see each other's file, and an
    ordinary build passes no --overrides and reads none -- staleness is impossible
    rather than cleaned up."""
    lines = ["# %s" % BANNER,
             "# The --set overrides this build resolved with, recorded verbatim so",
             "# `check` re-resolves from the same inputs. Pass it with --overrides;",
             "# it is never discovered by searching.",
             "# app=%s platform=%s resolved-hash=%s" % (meta.get("app"), meta.get("platform"),
                                                        meta.get("caps_hash"))]
    for key in sorted(overrides):
        lines.append("%s=%d" % (key, overrides[key]))
    lines.append("")
    path = os.path.join(out, "overrides.caps")
    _write(path, "\n".join(lines))
    return path


def parse_overrides(path):
    from resolve import parse_manifest
    return {k: v for k, v, _ in parse_manifest(path)}


