def _camel(key):
    """MT_FFMPEG_DECODERS_WITHHELD -> MTFFmpegDecodersWithheld, matching the
    MTFFmpegBuildMode / MTReleaseSymbols properties beside it."""
    parts = key.split("_")
    out = "MT" + ("FFmpeg" if parts[1] == "FFMPEG" else parts[1].capitalize())
    for p in parts[2:]:
        out += p.capitalize()
    return out


def ffmpeg_policy(vocab, values):
    """The FFmpeg decoder policy for the resolved mode, as four space-separated
    lists: decoders, parsers, demuxers, and the withheld set.

    ONE SHAPE FOR ALL OF THEM, and it is the shape MT_FFMPEG_BUILD_MODE
    already uses -- a space-separated string, not a CMake `;`-list -- because
    the three readers that carry these values into the codec scripts parse
    fragments line by line with a sed and two regexes. A second shape would
    mean a second parser in each of them.

    The withheld set is emitted SEPARATELY from the decoder list rather than
    folded into it, because the scripts need both: the configure line wants
    the union for `full`, and the guard wants to know which names are the
    withheld ones. Deriving one from the other in three scripts is how the
    lists drifted apart in the first place.
    """
    ff = vocab.get("MT_CAP_VIDEO_PLAYBACK").get("ffmpeg", {})
    full = ffmpeg_mode(values) == "full"
    decoders = list(ff.get("decoders_base", []))
    parsers = list(ff.get("parsers_base", []))
    if full:
        decoders += ff.get("decoders_withheld", [])
        parsers += ff.get("parsers_withheld", [])
    return {
        "MT_FFMPEG_DECODERS": " ".join(decoders),
        "MT_FFMPEG_PARSERS": " ".join(parsers),
        "MT_FFMPEG_DEMUXERS": " ".join(ff.get("demuxers", [])),
        "MT_FFMPEG_DECODERS_WITHHELD": " ".join(ff.get("decoders_withheld", [])),
    }


def cmake_path(path):
    r"""A path CMake can read on every platform.

    CMake parses `\U` inside a quoted argument as a character escape and fails
    the whole fragment, so a Windows path spelled with backslashes is a syntax
    error rather than a wrong value. Forward slashes are accepted everywhere
    CMake accepts a path, on Windows included.
    """
    return path.replace("\\", "/")


def emit_cmake(vocab, values, canonical, out, include_dir, meta=None):
    lines = ["# %s" % BANNER, ""]
    lines.append('set(MT_CAPS_RESOLVED "%s")' % canonical)
    lines.append('set(MT_CAPS_INCLUDE_DIR "%s")' % cmake_path(include_dir))
    lines.append('set(MT_CAPS_BUILD_DIR "%s")' % cmake_path(os.path.dirname(include_dir)))
    lines.append("")
    lines.append("# Capabilities, as CMake variables AND as compile definitions.")
    for key in vocab.keys:
        lines.append("set(%s %d)" % (key, values[key]))
    lines.append("")
    lines.append("# Library flags. Every known flag appears, on or OFF: emitting only")
    lines.append("# the on ones leaves the rest UNDEFINED, and the #ifdef family")
    lines.append('# defaults off while the value style defaults on -- so "absent"')
    lines.append("# means two different things depending on the guard it meets.")
    flags = enabled_flags(vocab, values, platform=(meta or {}).get("platform"))
    for flag, value in flags.items():
        lines.append("set(%s %d)" % (flag, value))
    lines.append("")
    lines.append("# The KEYS, not a frozen list of KEY=VALUE pairs.")
    lines.append("#")
    lines.append("# mt_apply_capabilities re-reads each variable's CURRENT value at call")
    lines.append("# time. A baked list would freeze the values as of generation, and")
    lines.append("# CMakeLists.txt can still legitimately change one afterwards -- the")
    lines.append("# libheif downgrade does exactly that. With a frozen list the engine")
    lines.append("# would compile every TU with MT_ENABLE_LIBHEIF=1 while neither the")
    lines.append("# include dirs nor the library were added: a hard failure behind a")
    lines.append("# warning that claimed the feature had been disabled.")
    lines.append("set(MT_CAPS_CAPABILITY_KEYS")
    for key in vocab.keys:
        lines.append("    %s" % key)
    lines.append(")")
    lines.append("set(MT_CAPS_FLAG_KEYS")
    for flag in flags:
        lines.append("    %s" % flag)
    lines.append(")")
    lines.append("set(MT_CAPS_COMMERCIAL %d)" % values[COMMERCIAL_KEY])
    lines.append("set(MT_CAPS_PRIVATE %d)" % values[PRIVATE_KEY])
    lines.append("# Build-settings mode values (decision 0.5 / 0.2) -- values, not defines.")
    lines.append("set(MT_RELEASE_SYMBOLS %d)" % values[SYMBOLS_KEY])
    lines.append('set(MT_FFMPEG_BUILD_MODE "%s")' % ffmpeg_mode(values))
    for k, v in sorted(ffmpeg_policy(vocab, values).items()):
        lines.append('set(%s "%s")' % (k, v))
    # Through cmake_path, like MT_CAPS_INCLUDE_DIR above. The store paths are
    # the first ABSOLUTE paths this fragment carried that are not already
    # normalised, and on Windows they broke it outright (`C:\Users\...`).
    for k, v in sorted(store_settings(meta or {}).items()):
        lines.append('set(%s "%s")' % (k, cmake_path(v)))
    lines.append("")
    lines.append("function(mt_apply_capabilities target)")
    lines.append("    set(_mt_defs \"\")")
    lines.append("    foreach(_k IN LISTS MT_CAPS_CAPABILITY_KEYS MT_CAPS_FLAG_KEYS)")
    lines.append("        # ${_k} expands to the NAME, so if(${_k}) tests the variable.")
    lines.append("        if(${_k})")
    lines.append("            list(APPEND _mt_defs \"${_k}=1\")")
    lines.append("        else()")
    lines.append("            list(APPEND _mt_defs \"${_k}=0\")")
    lines.append("        endif()")
    lines.append("    endforeach()")
    lines.append("")
    lines.append("    # MT_COMMERCIAL_BUILD is ABSENT when the mode is off, never =0. Every")
    lines.append("    # guard on it in the tree is presence-style, and `#ifdef X` is TRUE")
    lines.append("    # when X is defined as 0 -- so emitting =0 would take all 30 sites")
    lines.append("    # down the COMMERCIAL branch, including the licence-audit tests")
    lines.append("    # written to catch exactly that.")
    lines.append("    if(MT_CAPS_COMMERCIAL)")
    lines.append("        list(APPEND _mt_defs MT_COMMERCIAL_BUILD=1)")
    lines.append("    endif()")
    lines.append("    # MT_PRIVATE_BUILD: same presence-style rule, same reason.")
    lines.append("    if(MT_CAPS_PRIVATE)")
    lines.append("        list(APPEND _mt_defs MT_PRIVATE_BUILD=1)")
    lines.append("    endif()")
    lines.append("")
    lines.append("    target_compile_definitions(${target} PUBLIC ${_mt_defs})")
    lines.append('    target_include_directories(${target} PUBLIC "${MT_CAPS_INCLUDE_DIR}")')
    lines.append("endfunction()")
    lines.append("")

    path = os.path.join(out, "MTEngineCapabilities.cmake")
    _write(path, "\n".join(lines))
    return path


# ---------------------------------------------------------------------------
# macOS -- xcconfig
#
# NOT imported by any Xcode project. A baseConfigurationReference is a tracked
# path and $MT_OUT ends in <caps-hash>, so no tracked reference can name this
# file. It is an artefact the WRAPPER reads and turns into xcodebuild settings.
# What carries a baseConfigurationReference is a *tracked* xcconfig holding the
# target's own defaults plus the consumption line
#   GCC_PREPROCESSOR_DEFINITIONS = $(inherited) $(MT_CAPS_DEFINES)
# Two files, two jobs, one name -- which is what three earlier drafts confused.
#
# So this file emits each value as a STANDALONE assignment the wrapper can read
# back, and folds nothing into GCC_PREPROCESSOR_DEFINITIONS.
# ---------------------------------------------------------------------------

def emit_xcconfig(vocab, values, canonical, out, include_dir, meta=None):
    lines = ["// %s" % BANNER,
             "//",
             "// This file is READ BY build-macos.sh and imported by nothing. See emit.py.",
             ""]
    for key in vocab.keys:
        lines.append("%s = %d" % (key, values[key]))
    lines.append("")
    for flag, value in enabled_flags(vocab, values, platform=(meta or {}).get("platform")).items():
        lines.append("%s = %d" % (flag, value))
    lines.append("")
    # Build-settings mode values -- VALUES only, never defines: decision 0.5
    # says nothing may guard code on the symbols key, and the ffmpeg mode is a
    # script input, not a compile-time branch.
    lines.append("MT_RELEASE_SYMBOLS = %d" % values[SYMBOLS_KEY])
    lines.append("MT_FFMPEG_BUILD_MODE = %s" % ffmpeg_mode(values))
    for k, v in sorted(ffmpeg_policy(vocab, values).items()):
        lines.append("%s = %s" % (k, v))
    for k, v in sorted(store_settings(meta or {}).items()):
        lines.append("%s = %s" % (k, v))
    lines.append("")
    lines.append("MT_CAPS_DEFINES = %s" % " ".join(
        app_visible_defines(vocab, values, platform=(meta or {}).get("platform"))))
    lines.append("MT_CAPS_DEFINES_ENGINE = %s" % " ".join(engine_only_defines(vocab, values)))
    lines.append("MT_CAPS_INCLUDE_DIR = %s" % include_dir)
    lines.append("MT_CAPS_BUILD_DIR = %s" % os.path.dirname(include_dir))
    lines.append("MT_CAPS_RESOLVED = %s" % canonical)
    lines.append("")

    path = os.path.join(out, "MTEngineCaps.xcconfig")
    _write(path, "\n".join(lines))
    return path


