def emit_props(vocab, values, canonical, out, include_dir, meta=None):
    # platform="windows": this fragment is imported ONLY by MSBuild (see the
    # section header below), so it always reflects Windows reality, regardless
    # of which --platform a given `resolve` invocation happened to run under.
    # See PLATFORM_UNAVAILABLE_FLAGS in resolve.py for why.
    defines = []
    for key in vocab.keys:
        defines.append("%s=%d" % (key, values[key]))
    for flag, value in enabled_flags(vocab, values, platform=(meta or {}).get("platform", "windows")).items():
        defines.append("%s=%d" % (flag, value))
    if values[COMMERCIAL_KEY] == 1:
        defines.append("MT_COMMERCIAL_BUILD=1")
    # Presence-style, same as above: absent when off, never =0.
    if values[PRIVATE_KEY] == 1:
        defines.append("MT_PRIVATE_BUILD=1")

    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        "<!-- %s -->" % BANNER,
        '<Project ToolsVersion="4.0" xmlns="http://schemas.microsoft.com/developer/msbuild/2003">',
        "  <PropertyGroup>",
        "    <MTCapsResolved>%s</MTCapsResolved>" % canonical,
        "    <MTCapsIncludeDir>%s</MTCapsIncludeDir>" % include_dir,
        "    <MTCapsBuildDir>%s</MTCapsBuildDir>" % os.path.dirname(include_dir),
        "    <MTReleaseSymbols>%d</MTReleaseSymbols>" % values[SYMBOLS_KEY],
        "    <MTFFmpegBuildMode>%s</MTFFmpegBuildMode>" % ffmpeg_mode(values),
    ] + [
        # MSBuild property names cannot carry the MT_FFMPEG_ prefix's
        # underscores by convention here, so they follow the CamelCase of
        # their neighbours; the codec script reads them through the
        # environment the driver builds, not from this file.
        "    <%s>%s</%s>" % (_camel(k), v, _camel(k))
        for k, v in sorted(ffmpeg_policy(vocab, values).items())
    ] + [
        # Per-unit stores, so an IDE build reaches the same directories the
        # driver does. MTStoreSdl3, MTStoreVideoCodecs, ...
        "    <%s>%s</%s>" % (_camel(k), v, _camel(k))
        for k, v in sorted(store_settings(meta or {}).items())
    ] + [
        "  </PropertyGroup>",
        "  <PropertyGroup>",
    ]
    for key in vocab.keys:
        lines.append("    <%s>%d</%s>" % (key, values[key], key))
    for flag, value in enabled_flags(vocab, values, platform="windows").items():
        lines.append("    <%s>%d</%s>" % (flag, value, flag))
    lines += [
        "  </PropertyGroup>",
        "  <ItemDefinitionGroup>",
        "    <ClCompile>",
        "      <PreprocessorDefinitions>%s;%%(PreprocessorDefinitions)</PreprocessorDefinitions>"
        % ";".join(defines),
        "      <AdditionalIncludeDirectories>$(MTCapsIncludeDir);%(AdditionalIncludeDirectories)</AdditionalIncludeDirectories>",
        "      <!-- Decision 0.5: debug info is ALWAYS generated (the app",
        "           projects carried no GenerateDebugInformation at all, so",
        "           Release links emitted no PDB); MT_RELEASE_SYMBOLS decides",
        "           only whether the PDB SHIPS, and the driver's deploy stage",
        "           enforces that half. -->",
        "      <DebugInformationFormat>ProgramDatabase</DebugInformationFormat>",
        "    </ClCompile>",
        "    <Link>",
        "      <GenerateDebugInformation>true</GenerateDebugInformation>",
        "    </Link>",
        "  </ItemDefinitionGroup>",
        "</Project>",
        "",
    ]
    path = os.path.join(out, "MTEngineCaps.props")
    _write(path, "\n".join(lines))
    return path


