def emit_licenses(vocab, values, canonical, out, meta):
    """The SBOM, generated from the resolved set AND the core section.

    Derived from the resolved capability set ALONE it would be legally
    incomplete while looking complete: SDL3, zlib, ALSA, GTK3, freetype, libuv,
    ImGui, ImPlot and the committed prebuilts ship outside every capability key.
    That is worse than an obviously partial document, because nobody checks a
    document that appears finished. Both halves are emitted here and Phase 6's
    acceptance asserts both.

    Under the hard-error rule the set asked for and the set built are identical
    by construction, so this is one document describing both.
    """
    L = []
    A = L.append
    A("Third-party licences for %s" % meta.get("app", "(unknown app)"))
    A("=" * 72)
    A("")
    A("Generated by mtcaps from MTEngineSDL/tools/mtcaps/vocabulary.json.")
    A("Do not edit: regenerate instead.")
    A("")
    A("Build: platform=%s arch=%s config=%s mode=%s engine=%s"
      % (meta.get("platform"), meta.get("arch"), meta.get("config"),
         meta.get("mode"), meta.get("rev")))
    if meta.get("engine_options"):
        A("Engine options: %s"
          % ", ".join("%s=%s" % kv for kv in sorted(meta["engine_options"].items())))
        A("  (a CUDA build links NVIDIA components a CPU build does not, which is")
        A("   why these appear here as well as in the output path.)")
    A("")
    A("Resolved capability set:")
    A("  %s" % canonical)
    A("")

    A("-" * 72)
    A("CORE -- always present, belonging to no capability")
    A("-" * 72)
    A("")
    for dep in vocab.core["dependencies"]:
        A("  %s" % dep["name"])
        A("      licence   : %s" % dep["licence"])
        A("      version   : %s" % dep["version"])
        A("      provenance: %s" % dep["provenance"])
        A("")

    on = [k for k in vocab.keys if values[k] == 1]
    off = [k for k in vocab.keys if values[k] == 0]

    A("-" * 72)
    A("ENABLED CAPABILITIES")
    A("-" * 72)
    A("")
    any_dep = False
    for key in on:
        cap = vocab.get(key)
        deps = cap["dependencies"]
        A("  %s -- %s" % (key, cap["description"]))
        if not deps:
            A("      (no third-party dependency)")
        for dep in deps:
            any_dep = True
            A("      %s" % dep["name"])
            A("          licence   : %s" % dep["licence"])
            A("          version   : %s" % dep["version"])
            A("          provenance: %s" % dep["provenance"])
        comm = cap["commercial"]
        if comm["effect"] != "none" and values[COMMERCIAL_KEY] == 1:
            withheld = comm.get("forbidden_decoders_commercial", [])
            A("      commercial mode: %s%s"
              % (comm["effect"],
                 (" -- withheld: " + ", ".join(withheld)) if withheld else ""))
        A("")
    if not any_dep:
        A("  (no third-party dependencies among the enabled capabilities)")
        A("")

    # What the APPLICATION embeds that the vocabulary cannot know about. Read
    # from beside the manifest; absent means the app declares nothing, which
    # is a claim the app makes, not a default this document invents.
    app_deps = load_app_licences(meta["manifest"])
    if app_deps:
        A("-" * 72)
        A("APPLICATION -- declared by the app in %s" % APP_LICENCES_FILE)
        A("-" * 72)
        A("")
        for dep in app_deps:
            A("  %s" % dep["name"])
            A("      licence   : %s" % dep["licence"])
            A("      version   : %s" % dep["version"])
            A("      provenance: %s" % dep["provenance"])
            A("")

    A("-" * 72)
    A("DISABLED CAPABILITIES -- their dependencies are NOT in this build")
    A("-" * 72)
    A("")
    for key in off:
        deps = vocab.get(key)["dependencies"]
        A("  %s%s" % (key, (" (" + ", ".join(d["name"] for d in deps) + ")") if deps else ""))
    A("")

    path = os.path.join(out, "LICENSES.txt")
    _write(path, "\n".join(L) + "\n")
    return path


def emit_llama_version_placeholder(include_dir):
    """A PLACEHOLDER llama_cpp_version.h, so the header always exists.

    CGuiViewLlamaModelLoader.cpp includes it UNCONDITIONALLY, but
    build-llama_cpp.sh -- which used to write it, into a *tracked* file inside the
    engine checkout -- does not run at all when MT_CAP_LLM=0: it emits a stub
    archive and exits. Without this the capability-off build would fail on a
    missing include.

    Never overwrites: when llama IS built, that script writes the real
    `git describe` tag here afterwards and its value must survive re-resolves.
    """
    path = os.path.join(include_dir, "Sci", "Llama", "llama_cpp_version.h")
    if os.path.exists(path):
        return path
    _write(path,
           "// %s\n"
           "// Placeholder. build-llama_cpp.sh overwrites this with the real\n"
           "// `git describe` tag when llama.cpp is actually built.\n"
           "#pragma once\n"
           "#define MT_LLAMA_CPP_VERSION \"not-built\"\n" % BANNER)
    return path


def emit_msbuild_ide_defines(vocab, values, out):
    """Two bare files holding exactly what goes into <PreprocessorDefinitions>.

    They exist because of one MSBuild constraint. `<Import>` is evaluated during
    project EVALUATION, which completes strictly before any target runs -- so a
    Visual Studio build, which passes no /p:MTOutRoot, cannot import the
    generated .props for the build it is in.

    The way around it is not to import at all: a TARGET running BeforeTargets
    ClCompile can modify ClCompile item metadata, because those items are read by
    the task at EXECUTION time. That target needs the define list as a value it
    can read in one step, and MSBuild's property functions are a whitelist of
    static .NET methods -- File::ReadAllText is on it, an XML parse is not.

    So: one flat file per target kind, semicolon-separated, no trailing
    separator, nothing to parse.

    MT_COMMERCIAL_BUILD follows the same rule as everywhere else: present only
    when the mode is on, never as =0.

    platform="windows" throughout: this is the Visual Studio IDE channel and
    nothing else ever reads these two files. See PLATFORM_UNAVAILABLE_FLAGS
    in resolve.py.
    """
    app_defs = list(app_visible_defines(vocab, values, platform="windows"))
    engine_defs = list(app_defs) + list(engine_only_defines(vocab, values, platform="windows"))
    # The engine sees every flag; an app sees only what it guards on. Same split
    # the macOS channel makes, made here by writing two files instead of one.
    for name, defs in (("ide-defines-app.txt", app_defs),
                       ("ide-defines-engine.txt", engine_defs)):
        _write(os.path.join(out, name), ";".join(sorted(set(defs))) + "\n")
    return os.path.join(out, "ide-defines-engine.txt")
