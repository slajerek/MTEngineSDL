def emit_header(vocab, values, canonical, include_dir):
    caps = vocab.keys
    L = []
    A = L.append
    A("// %s" % BANNER)
    A("//")
    A("// ======================================================================")
    A("// WHAT THIS FILE IS FOR")
    A("// ======================================================================")
    A("//")
    A("// It lets APPLICATION SOURCE CODE ask about capabilities. That is a")
    A("// different job from the other four generated fragments, which tell a")
    A("// BUILD SYSTEM what to compile.")
    A("//")
    A("// NOTHING INCLUDES IT TODAY. That is expected, not an oversight: adopting")
    A("// it is app work, and no app has needed it yet. It is generated on every")
    A("// build so it is always correct and current when the first one does.")
    A("//")
    A("// It is NOT the idiom for engine internals. The engine gates itself on the")
    A("// MT_ENABLE_* library flags -- `#ifdef MT_ENABLE_FFMPEG` and friends --")
    A("// because those describe what it actually compiles. This header is the")
    A("// other side of the boundary: what the app ASKED for.")
    A("//")
    A("// TWO THINGS TO USE, and they answer different questions.")
    A("//")
    A("// 1. `MT_REQUIRE_CAP(MT_CAP_HTTP);` -- \"I cannot function without this.\"")
    A("//    A compile-time assertion. A manifest that turns the capability off")
    A("//    then fails to COMPILE, naming the capability, instead of linking and")
    A("//    failing at runtime somewhere unrelated. Put it at file scope in the")
    A("//    TU that depends on the capability.")
    A("//")
    A("// 2. `if (MT_HAS_CAP(MT_CAP_LLM)) { ... }` -- \"adapt to whatever I got.\"")
    A("//    A runtime query, for code that should degrade rather than refuse:")
    A("//    hide a menu item, skip a test, report what this binary supports.")
    A("//    It costs nothing at runtime -- the generated body is a switch over")
    A("//    literals the same run emitted, so the optimiser folds it away.")
    A("//")
    A("// Also here: `MT_GetCapabilityManifest()`, which returns the canonical")
    A("// resolved string this binary was built with. Useful in an about box, a")
    A("// crash report, or a test that wants to record the configuration it ran")
    A("// under.")
    A("//")
    A("// WHAT IS DELIBERATELY ABSENT: MT_COMMERCIAL_BUILD. See the note below.")
    A("//")
    A("// ======================================================================")
    A("//")
    A("// Per-build: this header lives under $MT_OUT/include/, keyed by engine")
    A("// revision, platform, arch, configuration, mode, backend and capability")
    A("// hash. No two builds sharing one engine checkout ever see each other's.")
    A("// It is never committed and never edited; regenerate it instead.")
    A("#pragma once")
    A("")
    A("// ---------------------------------------------------------------------")
    A("// Capabilities. MT_COMMERCIAL_BUILD is DELIBERATELY ABSENT from this file,")
    A("// in every form and at every value. It appears in the canonical resolved")
    A("// string below as 0 or 1 -- so the agreement check can tell \"off\" from")
    A("// \"unset\" -- and, when ON, as a -D on the build-system channel only.")
    A("// This header is on the include path of every engine and app TU, and every")
    A("// guard on that flag in the tree is presence-style: a #define ... 0 here")
    A("// would take all 30 sites down the COMMERCIAL branch, including the")
    A("// licence-audit tests written to catch exactly that.")
    A("// ---------------------------------------------------------------------")
    for key in caps:
        A("#define %-34s %d" % (key, values[key]))
    A("")
    A("// Known-name markers, so MT_REQUIRE_CAP can tell 0 from \"never heard of it\".")
    for key in caps:
        A("#define MT_CAP_DEFINED_%-20s 1" % key)
    A("")
    A("#ifdef __cplusplus")
    A("")
    A("// The enumerators CANNOT be the capability tokens: those are object-like")
    A("// macros defined above, so `enum class MTCapability { MT_CAP_LLM }` expands")
    A("// to `{ 0 }` and does not compile. Short names compile but cannot be reached")
    A("// from a ##-pasting macro, which is what the MT_CAP_ENUM_* aliases below are")
    A("// for. Both constraints, one shape.")
    A("enum class MTCapability")
    A("{")
    for key in caps:
        A("\t%s," % vocab.short(key))
    A("};")
    A("")
    for key in caps:
        A("#define MT_CAP_ENUM_%-22s ::MTCapability::%s" % (key, vocab.short(key)))
    A("")
    A("// `##` suppresses argument pre-expansion, so the call site passes the FULL")
    A("// token -- MT_REQUIRE_CAP(MT_CAP_LLM), never MT_REQUIRE_CAP(LLM). There is no")
    A("// preprocessor operation that strips a MT_CAP_ prefix.")
    A("//")
    A("// The macro expands to two DECLARATIONS and is not do{}while(0)-wrapped, so")
    A("// it belongs at file or class scope, or inside a braced block. Brace it when")
    A("// it follows an `if`: only the first declaration becomes the body, so a")
    A("// trailing `else` has nothing to attach to and you get `expected expression`.")
    A("// Bracing does NOT make the assertion conditional -- nothing can; static_assert")
    A("// is a compile-time construct and fires either way.")
    A("//")
    A("// The call site needs a trailing `;`: the second static_assert has none.")
    A("//")
    A("// A typo does NOT get the friendly message. MT_CAP_DEFINED_MT_CAP_TYPP is not")
    A("// a macro, so it survives as an undeclared identifier and the compiler says")
    A("// `use of undeclared identifier` -- static_assert only emits its message for a")
    A("// valid constant expression that evaluates false. No assert ordering fixes that.")
    A("#define MT_REQUIRE_CAP(cap) \\")
    A("\tstatic_assert(MT_CAP_DEFINED_##cap, #cap \" is not a known capability\"); \\")
    A("\tstatic_assert(cap, #cap \" is required by this host\")")
    A("")
    A("#define MT_HAS_CAP(cap) MT_HasCapability(MT_CAP_ENUM_##cap)")
    A("")
    A("// DEFINED here, not merely declared. `inline` makes it ODR-safe across TUs;")
    A("// a declaration alone links to nothing, and the one path that matters --")
    A("// MT_HAS_CAP -- is exactly the path a compile-only check never exercises.")
    A("inline bool MT_HasCapability(MTCapability cap)")
    A("{")
    A("\tswitch (cap)")
    A("\t{")
    for key in caps:
        A("\t\tcase ::MTCapability::%s: return %s;" % (vocab.short(key), key))
    A("\t}")
    A("\treturn false;")
    A("}")
    A("")
    A("// EXACTLY the canonical resolved form: semicolon-separated, sorted by byte")
    A("// value, no trailing separator. NOT newline-separated -- the in-target")
    A("// backstop compares this against --resolved, and two spellings of \"the same")
    A("// set\" is the mismatch the check exists to prevent.")
    A("inline const char *MT_GetCapabilityManifest()")
    A("{")
    A("\tstatic constexpr char kManifest[] =")
    # MUST track resolve.canonical_form()'s key list exactly -- including both
    # mode keys. These are string-literal CONTENT, not #defines, so they carry
    # none of the `#ifdef X` hazard that keeps MT_COMMERCIAL_BUILD out of this
    # header as a macro; and the backstop compares this text against
    # --resolved, so a key in one and not the other is a guaranteed mismatch.
    for i, key in enumerate(sorted(list(caps) + [COMMERCIAL_KEY, PRIVATE_KEY,
                                                 SYMBOLS_KEY])):
        sep = "" if i == 0 else ";"
        A("\t\t\"%s%s=%d\"" % (sep, key, values[key]))
    A("\t\t;")
    A("\treturn kManifest;")
    A("}")
    A("")
    A("#endif // __cplusplus")
    A("")

    path = os.path.join(include_dir, "MT_Capabilities.h")
    _write(path, "\n".join(L))
    return path


